var entity = catalog.Entity{Table: Table}

// Every printing of a spell: slugs equal once hyphens are removed (bigbys-hand, bigby-s-hand).
func versionsOf(arg func(any) string, slug string) string {
	return fmt.Sprintf("replace(t.slug, '-', '') = replace(%s, '-', '')", arg(slug))
}

// SpellRoutes serves the spell routes.
type SpellRoutes struct{ c *catalog.Handler }

// NewRoutes serves spells through the shared catalog handler.
func NewRoutes(c *catalog.Handler) *SpellRoutes { return &SpellRoutes{c: c} }

// ListSpells is GET /spells: a plain array, ordered by id (the list before /query existed).
func (h *SpellRoutes) ListSpells(w http.ResponseWriter, r *http.Request, p api.ListSpellsParams) {
	h.c.Array(w, r, entity, catalog.Params{Fields: p.Fields, Limit: p.Limit, Offset: p.Offset})
}

// QuerySpells is GET /spells/query.
func (h *SpellRoutes) QuerySpells(w http.ResponseWriter, r *http.Request, p api.QuerySpellsParams) {
	h.c.Query(w, r, entity,
		catalog.Params{Name: p.Name, Fields: p.Fields, Filter: p.Filter, Sort: p.Sort, Limit: p.Limit, Offset: p.Offset},
		catalog.Condition{Name: "versions_of", Value: p.VersionsOf, Where: versionsOf})
}

// ReadSpell is GET /spells/{entity_id}.
func (h *SpellRoutes) ReadSpell(w http.ResponseWriter, r *http.Request, id api.EntityId, p api.ReadSpellParams) {
	h.c.Read(w, r, entity, uuid.UUID(id), p.Fields)
}

// ReadSpellBySlugs is GET /spells/{source_slug}/{slug}.
func (h *SpellRoutes) ReadSpellBySlugs(w http.ResponseWriter, r *http.Request, sourceSlug, slug string, p api.ReadSpellBySlugsParams) {
	h.c.ReadBySlugs(w, r, entity, sourceSlug, slug, p.Fields)
}

// CreateSpell is POST /spells.
func (h *SpellRoutes) CreateSpell(w http.ResponseWriter, r *http.Request) { h.c.Create(w, r, entity) }

// ReplaceSpell is PUT /spells/{entity_id}.
func (h *SpellRoutes) ReplaceSpell(w http.ResponseWriter, r *http.Request, id api.EntityId) {
	h.c.Replace(w, r, entity, uuid.UUID(id))
}

// UpdateSpell is PATCH /spells/{entity_id}. vtt is replaced whole, not merged.
func (h *SpellRoutes) UpdateSpell(w http.ResponseWriter, r *http.Request, id api.EntityId) {
	h.c.Patch(w, r, entity, uuid.UUID(id))
}

// DeleteSpell is DELETE /spells/{entity_id}.
func (h *SpellRoutes) DeleteSpell(w http.ResponseWriter, r *http.Request, id api.EntityId) {
	h.c.Delete(w, r, entity, uuid.UUID(id))
}

// BulkLoadSpells is POST /spells/bulk.
func (h *SpellRoutes) BulkLoadSpells(w http.ResponseWriter, r *http.Request) { h.c.Bulk(w, r, entity) }
