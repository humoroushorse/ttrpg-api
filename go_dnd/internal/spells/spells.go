var schools = []string{
	"abjuration", "alteration", "conjuration", "divination", "enchantment",
	"evocation", "transmutation", "illusion", "invocation", "necromancy",
}

var vttSchema = vtt.MustLoad()

func checkSchool(v any) (any, error) {
	if !slices.Contains(schools, v.(string)) {
		return nil, fmt.Errorf("must be one of %v", schools)
	}
	return v, nil
}

func checkLevel(v any) (any, error) {
	if level := v.(int64); level < 0 || level > 9 {
		return nil, fmt.Errorf("must be 0 to 9")
	}
	return v, nil
}

// a fixed DC comes from the ETL as a number; the column is text
func dcAsText(v any) any {
	if n, ok := v.(json.Number); ok {
		return n.String()
	}
	return v
}

func checkVTT(v any) (any, error) { return vttSchema.Expand(v) }

